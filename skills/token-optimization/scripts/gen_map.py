#!/usr/bin/env python3
"""Generate a compact code map: each file's size and the summary from its header comment.

Each entry shows the file's approximate size and the first line of its header
comment, docstring or manifest description. Agents read the map to locate code instead of exploring directories, then read
a file's contract before its implementation. Files without a summary share one
line per directory. Bulky, generated and binary files are left out, and in a
git repo .gitignore is respected. With --check, exit 1 when the map is stale.

    gen_map.py --out docs/MAP.md          # write the map
    gen_map.py --out docs/MAP.md --check  # fail if it is out of date (for CI)
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

DEFAULT_EXCLUDES = (
    # dependencies and build output
    "node_modules/*", "*/node_modules/*", "target/*", "*/target/*", "dist/*", "*/dist/*",
    "vendor/*", "*/vendor/*", ".venv/*", "*/.venv/*", "venv/*", "*/venv/*", "*__pycache__/*",
    # lockfiles and generated artefacts
    "*.lock", "*-lock.json", "*-lock.yaml", "*.lockb", "go.sum", "*.min.js", "*.min.css", "*.map", "*.snap",
    # media, archives, fonts and binaries
    "*.png", "*.jpg", "*.jpeg", "*.gif", "*.webp", "*.ico", "*.svg", "*.pdf",
    "*.zip", "*.gz", "*.tgz", "*.xz", "*.zst", "*.tar", "*.woff", "*.woff2", "*.ttf", "*.otf",
    "*.so", "*.dylib", "*.dll", "*.exe", "*.wasm", "*.bin",
)
SKIP_DIRS = {".git", "node_modules", "target", "dist", "vendor", ".venv", "venv", "__pycache__"}
HEAD_BYTES = 8192
MAX_BYTES = 2_000_000
MAX_SUMMARY = 100

HASH = {".sh", ".bash", ".zsh", ".fish", ".rb", ".pl", ".r", ".yaml", ".yml", ".toml", ".nix",
        ".tf", ".ps1", ".cfg", ".conf", ".ini", ".mk", ".cmake", ".just"}
HASH_NAMES = {"Makefile", "Dockerfile", "Containerfile", "justfile", "Justfile", "Rakefile", "Gemfile"}
SLASH = {".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".mts", ".cts", ".go", ".rs", ".java", ".kt", ".kts",
         ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".hh", ".cs", ".swift", ".scala", ".dart", ".uc",
         ".zig", ".proto", ".css", ".scss", ".less", ".php", ".groovy", ".gradle", ".sol", ".jsonc"}
DASH = {".sql", ".lua", ".hs", ".elm"}
MARKDOWN = {".md", ".mdx", ".markdown"}
MANIFESTS = {"package.json", "composer.json", "Cargo.toml", "pyproject.toml"}

_NOISE = re.compile(
    r"^(copyright|\(c\)|©|spdx-license-identifier|licensed under|license:|@license|eslint[- ]|prettier-ignore|"
    r"biome-ignore|@ts-|jshint|tslint:|istanbul ignore|c8 ignore|noqa|type: ?ignore|pylint:|mypy:|"
    r"fmt: ?(off|on|skip)|-\*-|vim:|shellcheck |nolint|go:build|\+build|@flow|@jsx|@format|<reference|"
    r"#?region\b|#?endregion\b|syntax=)",
    re.IGNORECASE)
_DOC_TAG = re.compile(r"^@(file|fileoverview|overview|module|description|brief|summary)\b:?\s*", re.IGNORECASE)
_GENERATED = re.compile(r"@generated|do not edit|code generated by", re.IGNORECASE)
_TOML_DESCRIPTION = re.compile(r'^\s*description\s*=\s*"([^"]*)"', re.MULTILINE)
_PY_DOCSTRING = re.compile(r'^[rRuUbBfF]{0,2}("""|\'\'\'|"|\')(.*)$')
_SKIP_LINES = {'"use strict";', "'use strict';", '"use client";', "'use client';", '"use server";', "'use server';"}


@dataclass(frozen=True)
class Entry:
    path: str  # POSIX path relative to the root
    lines: int | None  # None when the file is too large to count
    size: int  # bytes
    summary: str | None
    generated: bool


def clean(text: str) -> str | None:
    """Normalize one comment line; None if it carries no description."""
    text = " ".join(text.replace("*/", " ").split())
    if not any(ch.isalnum() for ch in text) or _NOISE.match(text):
        return None
    untagged = _DOC_TAG.sub("", text)
    if untagged == text and text.startswith("@"):
        return None
    text = untagged
    if not text:
        return None
    return text if len(text) <= MAX_SUMMARY else text[: MAX_SUMMARY - 1].rstrip() + "…"


def _hash_summary(lines: list[str]) -> str | None:
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#!") or line == "---":
            continue
        if not line.startswith("#"):
            return None
        summary = clean(line.lstrip("#"))
        if summary:
            return summary
    return None


def _dash_summary(lines: list[str]) -> str | None:
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#!"):
            continue
        if not line.startswith("--"):
            return None
        summary = clean(line.lstrip("-"))
        if summary:
            return summary
    return None


def _slash_summary(lines: list[str]) -> str | None:
    in_block = False
    for raw in lines:
        line = raw.strip()
        if in_block:
            in_block = "*/" not in line
            summary = clean(line.split("*/", 1)[0].lstrip("*"))
        elif not line or line.startswith("#!") or line in _SKIP_LINES:
            continue
        elif line.startswith("//"):
            summary = clean(line.lstrip("/").lstrip("!"))
        elif line.startswith("/*"):
            body = line[2:].lstrip("*!")
            in_block = "*/" not in body
            summary = clean(body.split("*/", 1)[0])
        else:
            return None
        if summary:
            return summary
    return None


def _python_summary(lines: list[str]) -> str | None:
    for index, raw in enumerate(lines):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _PY_DOCSTRING.match(line)
        if not match:
            break
        quote, rest = match.groups()
        if quote in rest:
            return clean(rest.split(quote, 1)[0])
        summary = clean(rest)
        if summary:
            return summary
        for following in lines[index + 1:]:
            summary = clean(following.split(quote, 1)[0])
            if summary or quote in following:
                return summary
        return None
    return _hash_summary(lines)


def _markdown_summary(lines: list[str]) -> str | None:
    in_front_matter = bool(lines) and lines[0].strip() == "---"
    for raw in lines[1:] if in_front_matter else lines:
        line = raw.strip()
        if in_front_matter:
            in_front_matter = line != "---"
        elif line.startswith("#"):
            return clean(line.lstrip("#"))
    return None


def _manifest_summary(name: str, text: str) -> str | None:
    if name.endswith(".json"):
        try:
            data = json.loads(text)
        except ValueError:
            return None
        description = data.get("description") if isinstance(data, dict) else None
        return clean(description) if isinstance(description, str) else None
    match = _TOML_DESCRIPTION.search(text)
    return clean(match.group(1)) if match else None


def summarize(name: str, text: str) -> str | None:
    """The one-line summary from a file's header comment, docstring or manifest description."""
    base = name.rsplit("/", 1)[-1]
    ext = os.path.splitext(base)[1].lower()
    lines = text.splitlines()
    shebang = lines[0] if lines and lines[0].startswith("#!") else ""
    if base in MANIFESTS:
        return _manifest_summary(base, text)
    if ext in (".py", ".pyi") or (not ext and "python" in shebang):
        return _python_summary(lines)
    if ext in SLASH:
        return _slash_summary(lines)
    if ext in HASH or base in HASH_NAMES or (not ext and shebang):
        return _hash_summary(lines)
    if ext in DASH:
        return _dash_summary(lines)
    if ext in MARKDOWN:
        return _markdown_summary(lines)
    return None


def size_label(lines: int | None, size: int, mode: str) -> str | None:
    """'<50', '~150' (approx), '143' (exact), None (none), or MB for files too large to count."""
    if mode == "none":
        return None
    if lines is None:
        return f"{size / 1_000_000:.1f} MB"
    if mode == "exact":
        return str(lines)
    return "<50" if lines < 50 else f"~{(lines + 25) // 50 * 50}"


def list_files(root: Path) -> list[str]:
    """Paths relative to root: from git (respecting .gitignore) when possible, else a directory walk."""
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True, check=True)
        return sorted({p for p in result.stdout.decode("utf-8", "surrogateescape").split("\0") if p})
    except (OSError, subprocess.CalledProcessError):
        pass
    paths = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        relative = Path(dirpath).relative_to(root)
        paths.extend((relative / name).as_posix() for name in filenames)
    return sorted(paths)


def scan(root: Path, excludes, skip: set[str]) -> list[Entry]:
    entries = []
    for rel in list_files(root):
        if rel in skip or any(fnmatch.fnmatch(rel, pattern) for pattern in excludes):
            continue
        path = root / rel
        if not path.is_file():
            continue
        try:
            size = path.stat().st_size
            with path.open("rb") as handle:
                head = handle.read(HEAD_BYTES)
                if b"\0" in head:
                    continue  # binary
                if size > MAX_BYTES:
                    entries.append(Entry(rel, None, size, None, False))
                    continue
                data = head + handle.read()
        except OSError:
            continue
        lines = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
        name = rel.rsplit("/", 1)[-1]
        text = (data if name in MANIFESTS else head).decode("utf-8", "replace")
        generated = bool(_GENERATED.search("\n".join(text.splitlines()[:5])))
        summary = None if generated else summarize(rel, text)
        entries.append(Entry(rel, lines, size, summary, generated))
    return entries


def render(entries: list[Entry], size_mode: str, max_other: int) -> str:
    by_dir = defaultdict(list)
    for entry in entries:
        by_dir[entry.path.rsplit("/", 1)[0] if "/" in entry.path else "."].append(entry)
    size_note = {"approx": " (approximate lines)", "exact": " (lines)", "none": ""}[size_mode]
    out = ["# Code map", "",
           "Generated by gen_map.py from the token-optimization skill; do not edit by hand. "
           f"Entries: file{size_note} — summary from its header comment.", ""]

    def label(entry: Entry) -> str:
        size = size_label(entry.lines, entry.size, size_mode)
        text = f"`{entry.path.rsplit('/', 1)[-1]}`" + (f" ({size})" if size else "")
        return text + (" (generated)" if entry.generated else "")

    for directory in sorted(by_dir, key=lambda d: (d != ".", d)):
        out.append("## ./" if directory == "." else f"## {directory}/")
        others = []
        for entry in sorted(by_dir[directory], key=lambda e: e.path):
            if entry.summary:
                out.append(f"- {label(entry)} — {entry.summary}")
            else:
                others.append(entry)
        if others:
            more = len(others) - max_other
            shown = ", ".join(label(entry) for entry in others[:max_other])
            out.append(f"- also: {shown}" + (f", and {more} more" if more > 0 else ""))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def build_map(root: Path, out: Path | None = None, excludes=(), size_mode="approx", max_other=12) -> str:
    root = root.resolve()
    skip = set()
    if out is not None:
        try:
            skip.add(out.resolve().relative_to(root).as_posix())
        except ValueError:
            pass  # the map lives outside the root
    return render(scan(root, (*DEFAULT_EXCLUDES, *excludes), skip), size_mode, max_other)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a compact code map: file, size and header summary.")
    parser.add_argument("--root", type=Path, default=Path("."), help="directory to map; default: current directory")
    parser.add_argument("--out", type=Path, help="write the map here, e.g. docs/MAP.md; default: stdout")
    parser.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh map")
    parser.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                        help="another glob to leave out (repeatable)")
    parser.add_argument("--lines", choices=("approx", "exact", "none"), default="approx",
                        help="how to show file sizes; default approx (stable under small edits)")
    parser.add_argument("--max-other", type=int, default=12,
                        help="files without a summary to list per directory; default 12")
    args = parser.parse_args(argv)
    if args.check and args.out is None:
        parser.error("--check needs --out")
    text = build_map(args.root, args.out, args.exclude, args.lines, args.max_other)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else None
        if current != text:
            print(f"{args.out} is stale; regenerate it with gen_map.py --out {args.out}", file=sys.stderr)
            return 1
        return 0
    if args.out is None:
        sys.stdout.write(text)
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        with args.out.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
