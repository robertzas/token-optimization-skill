class Summaries(unittest.TestCase):
    cases = [
        ("lib.rs", "#![forbid(unsafe_code)]\n//! Pure domain types.\n//!\n//! More detail.\nuse std::fmt;\n",
         "Pure domain types."),
        ("m.py", '#!/usr/bin/env python3\n"""Parse UCI files."""\n', "Parse UCI files."),
        ("m.py", '"""\nParse UCI files.\n\nDetails.\n"""\nimport os\n', "Parse UCI files."),
        ("m.py", "# Helpers for tests.\nimport os\n", "Helpers for tests."),
        ("m.py", "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nimport os\n", None),
        ("a.ts", "// SPDX-License-Identifier: MIT\n/**\n * @file Topology layout engine.\n */\nexport {};\n",
         "Topology layout engine."),
        ("a.js", "/*\n * Copyright 2026 Someone\n */\n/** Renders the device table. */\nexport {};\n",
         "Renders the device table."),
        ("a.tsx", "'use client';\n// Device list page.\n", "Device list page."),
        ("a.ts", "export const x = 1;\n// a late comment\n", None),
        ("doc.go", "// Package uci parses UCI config.\npackage uci\n", "Package uci parses UCI config."),
        ("push.sh", "#!/bin/sh\n# Push the agent to a node.\nset -eu\n", "Push the agent to a node."),
        ("deploy", "#!/usr/bin/env bash\n# Deploy the controller.\n", "Deploy the controller."),
        ("q.sql", "-- Rollups per hour.\nselect 1;\n", "Rollups per hour."),
        ("README.md", "---\ntitle: x\n---\n# Token optimization\n\nText.\n", "Token optimization"),
        ("package.json", '{"name": "web", "description": "SolidJS UI"}', "SolidJS UI"),
        ("Cargo.toml", '[package]\nname = "core"\ndescription = "Pure core"\n', "Pure core"),
        ("notes.txt", "Just text.\n", None),
    ]

    def test_cases(self):
        for name, text, expected in self.cases:
            with self.subTest(name=name, text=text):
                self.assertEqual(gm.summarize(name, text), expected)

    def test_long_summary_is_truncated(self):
        summary = gm.summarize("a.ts", "// " + "word " * 40 + "\n")
        self.assertLessEqual(len(summary), gm.MAX_SUMMARY)
        self.assertTrue(summary.endswith("…"))


class SizeLabel(unittest.TestCase):
    def test_modes(self):
        self.assertEqual(gm.size_label(3, 30, "approx"), "<50")
        self.assertEqual(gm.size_label(140, 3_000, "approx"), "~150")
        self.assertEqual(gm.size_label(176, 3_000, "approx"), "~200")
        self.assertEqual(gm.size_label(140, 3_000, "exact"), "140")
        self.assertIsNone(gm.size_label(140, 3_000, "none"))
        self.assertEqual(gm.size_label(None, 2_500_000, "approx"), "2.5 MB")


class BuildMap(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        files = {
            "src/lib.rs": "//! Core types.\npub struct Node;\n",
            "src/util.rs": "pub fn helper() {}\n",
            "src/gen.ts": "// @generated by ts-rs. Do not edit.\nexport type X = 1;\n",
            "Cargo.lock": "# lock\n",
            "node_modules/x/index.js": "// Should never be listed.\n",
            "README.md": "# Demo project\n",
        }
        for rel, text in files.items():
            path = self.root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        (self.root / "blob.dat").write_bytes(b"\x00\x01binary")

    def tearDown(self):
        self.tmp.cleanup()

    def test_lists_summaries_and_leaves_out_noise(self):
        text = gm.build_map(self.root)
        self.assertIn("## ./\n- `README.md` (<50) — Demo project\n", text)
        self.assertIn("- `lib.rs` (<50) — Core types.", text)
        self.assertIn("- also: `gen.ts` (<50) (generated), `util.rs` (<50)", text)
        for absent in ("Cargo.lock", "node_modules", "blob.dat", "Should never"):
            self.assertNotIn(absent, text)

    def test_check_detects_a_stale_map(self):
        out = self.root / "docs" / "MAP.md"
        args = ["--root", str(self.root), "--out", str(out)]
        self.assertEqual(gm.main(args), 0)
        self.assertNotIn("MAP.md", out.read_text(encoding="utf-8"))
        self.assertEqual(gm.main(args + ["--check"]), 0)
        (self.root / "src" / "new.rs").write_text("//! New module.\n", encoding="utf-8")
        with contextlib.redirect_stderr(io.StringIO()) as stderr:
            self.assertEqual(gm.main(args + ["--check"]), 1)
        self.assertIn("is stale", stderr.getvalue())

    def test_git_repo_respects_gitignore(self):
        if shutil.which("git") is None:
            self.skipTest("git is not installed")
        subprocess.run(["git", "init", "-q", str(self.root)], check=True)
        (self.root / ".gitignore").write_text("secret/\n", encoding="utf-8")
        (self.root / "secret").mkdir()
        (self.root / "secret" / "keys.py").write_text('"""Hidden module."""\n', encoding="utf-8")
        text = gm.build_map(self.root)
        self.assertNotIn("Hidden module", text)
        self.assertIn("Core types.", text)


